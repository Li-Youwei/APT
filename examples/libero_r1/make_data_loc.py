"""Write data_utils/data_loc.local.yaml for the R1 server (spec 3.2).

Copies every entry of the checked-in template (non-LIBERO entries must exist:
some dataset classes resolve their path at import time), sets the host key,
and points the four LIBERO entries at the converted data:

  python -m examples.libero_r1.make_data_loc --root /data/libero_apt --host r1
  export APT_DATA_LOC_HOST=r1     # in every shell that imports data_utils
"""
from __future__ import annotations

import argparse
import os

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
SUITE_DIRS = {"LiberoSpatial": "libero_spatial", "LiberoObject": "libero_object",
              "LiberoGoal": "libero_goal", "Libero10": "libero_10"}


def main(args):
    with open(os.path.join(REPO, "data_utils", "data_loc.yaml")) as fp:
        tmpl = yaml.safe_load(fp)
    block = dict(next(iter(tmpl["hosts"].values())))
    root = os.path.abspath(args.root)
    for name, sub in SUITE_DIRS.items():
        block[name] = os.path.join(root, sub, "**", "*.h5")
    out = os.path.join(REPO, "data_utils", "data_loc.local.yaml")
    if os.path.exists(out) and not args.force:
        raise SystemExit(f"{out} exists; pass --force to overwrite")
    with open(out, "w") as fp:
        fp.write("# generated by examples/libero_r1/make_data_loc.py (gitignored)\n")
        yaml.safe_dump({"hosts": {args.host: block}}, fp, sort_keys=False)
    print(f"[OK] wrote {out}; now `export APT_DATA_LOC_HOST={args.host}`")
    for name in SUITE_DIRS:
        print(f"  {name}: {block[name]}")


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--root", required=True, help="--out_root used by convert_libero")
    p.add_argument("--host", default="r1")
    p.add_argument("--force", action="store_true")
    main(p.parse_args())
